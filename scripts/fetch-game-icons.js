#!/usr/bin/env node
/**
 * Regenerates frontend/src/components/art/game-icons.ts from game-icons.net.
 *
 * Run from the repo root: `node scripts/fetch-game-icons.js`
 * Add an entry to ICONS to pull a new emblem; the key is what the components
 * refer to, the value is the upstream `<author>/<icon>` path.
 *
 * The upstream SVGs are 512×512 and open with a full-bleed background rect,
 * which is stripped here so the glyph alone is left.
 */
const fs = require('fs');
const path = require('path');
const https = require('https');

const ICONS = {
  // tier emblems — the ladder, read as a picture
  lifting: 'delapouite/weight-lifting-up',
  muscleUp: 'lorc/muscle-up',
  biceps: 'delapouite/biceps',
  laurels: 'lorc/laurels',
  crystal: 'lorc/crystal-shine',
  cutDiamond: 'lorc/cut-diamond',
  thorFist: 'lorc/thor-fist',
  wingedEmblem: 'lorc/winged-emblem',
  // ornament behind the top-tier crests
  angelWings: 'lorc/angel-wings',
  // equipment glyphs — the exercise-row thumbnail and the picker's filter chips
  // Chosen for silhouette at 17px, which is what these render at inside a boxed
  // list row — `lorc/lever` and `delapouite/spring` both looked right at 64px
  // and dissolved into hairlines at list size.
  pulley: 'delapouite/pulley-hook',
  gears: 'lorc/gears',
  strongArms: 'lorc/strong',
  coilSpring: 'delapouite/bouncing-spring',
  metalDisc: 'lorc/metal-disc',
  // medal emblems
  bolt: 'lorc/power-lightning',
  flame: 'lorc/fluffy-flame',
  weight: 'delapouite/weight',
  star: 'lorc/beveled-star',
  crown: 'lorc/crown',
  globe: 'delapouite/wireframe-globe',
  trophy: 'lorc/trophy',
  target: 'delapouite/convergence-target',
  calendar: 'delapouite/calendar',
  heart: 'delapouite/heart-beats',
  meal: 'delapouite/hot-meal',
  mountain: 'caro-asercion/mountain-climbing',
  shoe: 'delapouite/running-shoe',
  chart: 'delapouite/progression',
};

const AUTHOR_URL = {
  lorc: 'https://lorcblog.blogspot.com/',
  delapouite: 'https://delapouite.com/',
  'caro-asercion': 'https://game-icons.net/',
};

const OUT = path.join(__dirname, '..', 'frontend', 'src', 'components', 'art', 'game-icons.ts');
const BACKGROUND = /^M0 0h512v512H0z$/i;

const get = (url) =>
  new Promise((res, rej) =>
    https
      .get(url, { headers: { 'user-agent': 'reprush' } }, (r) => {
        if (r.statusCode !== 200) return rej(new Error(`${r.statusCode} ${url}`));
        let b = '';
        r.on('data', (c) => (b += c));
        r.on('end', () => res(b));
      })
      .on('error', rej),
  );

(async () => {
  const glyphs = {};
  for (const [key, src] of Object.entries(ICONS)) {
    const svg = await get(`https://raw.githubusercontent.com/game-icons/icons/master/${src}.svg`);
    const box = /viewBox="0 0 512 512"/.test(svg);
    if (!box) throw new Error(`${src}: unexpected viewBox, the 512 assumption is broken`);
    const d = Array.from(svg.matchAll(/\bd="([^"]+)"/g))
      .map((m) => m[1].replace(/\s+/g, ' ').trim())
      .filter((p) => !BACKGROUND.test(p));
    if (!d.length) throw new Error(`${src}: no glyph path`);
    glyphs[key] = { src, d: d.join(' ') };
    process.stderr.write(`  ${key} ← ${src}\n`);
  }

  const authors = Array.from(new Set(Object.values(ICONS).map((p) => p.split('/')[0]))).sort();

  const body = Object.entries(glyphs)
    .map(([k, v]) => `  ${k}: {\n    src: '${v.src}',\n    d: '${v.d.replace(/'/g, "\\'")}',\n  },`)
    .join('\n');

  fs.writeFileSync(
    OUT,
    `/**
 * Vendored glyphs from game-icons.net — CC BY 3.0.
 *
 * Generated by \`scripts/fetch-game-icons.js\`; do not hand-edit. These are the
 * emblems inside rank badges and medals. Hand-drawn versions flattened into
 * blobs at 48px, and this set is free, enormous and already game-flavoured.
 *
 * Attribution (required by the licence, and rendered in-app by
 * \`components/art/attribution.tsx\`):
${authors.map((a) => ` *   ${a} — ${AUTHOR_URL[a] ?? 'https://game-icons.net/'}`).join('\n')}
 * Licence: https://creativecommons.org/licenses/by/3.0/
 *
 * Every glyph is drawn in a 512×512 box with the vendor's full-bleed
 * background rect stripped, so \`GLYPH_BOX\` is the only scale you need.
 */

export const GLYPH_BOX = 512;

export interface Glyph {
  /** upstream path — the credit for this specific icon */
  src: string;
  d: string;
}

export const GLYPHS = {
${body}
} as const satisfies Record<string, Glyph>;

export type GlyphId = keyof typeof GLYPHS;

/** The credit line the licence asks for, kept next to the data it covers. */
export const GLYPH_CREDIT = {
  authors: [${authors.map((a) => `'${a}'`).join(', ')}],
  source: 'https://game-icons.net/',
  licence: 'CC BY 3.0',
  licenceUrl: 'https://creativecommons.org/licenses/by/3.0/',
} as const;
`,
  );
  process.stderr.write(`${Object.keys(glyphs).length} glyphs → ${OUT}\n`);
})();
